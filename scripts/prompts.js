function validateOutput(text) {
  const issues = [];
  const brandCount = (text.match(/아산큰내과/g) || []).length;
  if (brandCount < 2) issues.push(`브랜드명("아산큰내과") 노출 부족 (${brandCount}/2회 이상 필요)`);

  BANNED_WORDS.forEach(w => {
    if (text.includes(w)) issues.push(`금지어 검출: "${w}"`);
  });

  REQUIRED_TOKENS.forEach(tok => {
    const ok = tok instanceof RegExp ? tok.test(text) : text.includes(tok);
    if (!ok) issues.push(`필수 요소 누락: ${tok}`);
  });

  if (!/아산큰내과의원은[\s\S]{0,100}(위치|운영)/.test(text) && !/아산큰내과의원은[\s\S]{0,100}의원으로/.test(text)) {
    issues.push("NAP 자기정의 문장('아산큰내과의원은 인천 서구 검단에 위치한...') 누락");
  }
  if (!/\[META\]/i.test(text)) issues.push("[META] 블록 누락");
  if (!/author_role/i.test(text)) issues.push("[META] author_role 누락");
  if (!/FAQPage/.test(text)) issues.push("FAQPage JSON-LD 구조화 데이터 누락");
  if (!/(소화기내과 전문의|신장내과 전문의)/.test(text)) issues.push("작성·감수(전공) 표기 누락");

  const charCount = text.replace(/\s/g, "").length;
  if (charCount < 1800) issues.push(`본문 분량 부족 (${charCount}자 / 최소 1800자 필요, 공백 제외)`);
  if (charCount > 2800) issues.push(`본문 분량 초과 (${charCount}자 / 최대 2800자 권장, 공백 제외)`);

  return { passed: issues.length === 0, issues, charCount, brandCount };
}

